export function localizeConceptCategory(cat: string, lang?: string): string {
  const code = getLanguageCode(lang);
  if (code === 'ta') {
    if (cat === 'Foundation') return 'அடிப்படை நிலை';
    if (cat === 'Application') return 'பயன்பாட்டு நிலை';
    if (cat === 'Synthesis') return 'ஒருங்கிணைப்பு நிலை';
  }
  if (code === 'hi') {
    if (cat === 'Foundation') return 'नींव स्तर';
    if (cat === 'Application') return 'अनुप्रयोग स्तर';
    if (cat === 'Synthesis') return 'संश्लेषण स्तर';
  }
  return cat;
}

