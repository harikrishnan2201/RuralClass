export function localizeConceptNode(node: ConceptNode, lang?: string): ConceptNode {
  const code = getLanguageCode(lang);
  if (code === 'en') return node;

  const content = CONCEPT_NODE_CONTENT[node.id]?.[code];
  return {
    ...node,
    name: localizeTopicName(node.name, lang),
    category: localizeConceptCategory(node.category, lang) as any,
    status: localizeConceptStatus(node.status, lang) as any,
    description: content?.description || node.description,
    rootCauseContext: content?.rootCauseContext || node.rootCauseContext,
    suggestedAction: content?.suggestedAction || node.suggestedAction
  };
}

