export function localizeActivity(activity: Activity, lang?: string): Activity {
  const code = getLanguageCode(lang);
  if (code === 'en') return activity;

  const content = ACTIVITY_TRANSLATIONS[activity.id]?.[code];
  return {
    ...activity,
    title: content?.title || activity.title,
    objective: content?.objective || activity.objective,
    category: localizeActivityCategory(activity.category, lang) as any,
    requiredMaterials: activity.requiredMaterials.map(m => localizeResource(m, lang)),
    steps: content?.steps || activity.steps,
    adaptations: content?.adaptations || activity.adaptations.map(a => ({
      grade: localizeGrade(a.grade, lang),
      instruction: a.instruction
    }))
  };
}


